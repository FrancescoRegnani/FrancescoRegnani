-- Execute only in a NEW, dedicated PostgreSQL database, never in ABILITA.
create table if not exists events (
 id varchar(200) primary key, sport varchar(40) not null,
 player_a varchar(150) not null, player_b varchar(150) not null,
 starts_at timestamptz not null, is_demo boolean not null default false
);
create table if not exists odds_snapshots (
 id bigint generated by default as identity primary key,
 event_id varchar(200) not null references events(id),
 bookmaker varchar(100) not null, outcome varchar(150) not null,
 price double precision not null check(price > 1),
 observed_at timestamptz not null, is_demo boolean not null default false
);
create index if not exists ix_quotes_event_time on odds_snapshots(event_id, observed_at desc);
create table if not exists anomalies (
 id bigint generated by default as identity primary key,
 event_id varchar(200) not null references events(id), outcome varchar(150) not null,
 first_at timestamptz not null, last_at timestamptz not null,
 move_pp double precision not null, bookmakers integer not null,
 status varchar(30) not null default 'unexplained', is_demo boolean not null default false
);
create index if not exists ix_anomalies_event_time on anomalies(event_id,last_at desc);
create table if not exists news_evidence (
 id bigint generated by default as identity primary key,
 event_id varchar(200) not null references events(id),
 headline varchar(500) not null, source_url varchar(1000) not null,
 published_at timestamptz not null, category varchar(40) not null,
 assessment varchar(40) not null default 'unverified'
);
-- These tables are server-side only. If using Supabase public schema, RLS is essential.
alter table events enable row level security;
alter table odds_snapshots enable row level security;
alter table anomalies enable row level security;
alter table news_evidence enable row level security;
-- No anonymous or authenticated client policies. Backend uses a private DB connection.
